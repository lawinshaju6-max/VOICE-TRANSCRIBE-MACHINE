# --- LOWERCASE SUPPORT (Map to uppercase or clean proportional lowercase) ---
# Default behavior maps lowercase characters to corresponding uppercase single-stroke vectors
# to maintain high legible contrast on ruled paper.
for code in range(ord('a'), ord('z') + 1):
    char = chr(code)
    upper_char = char.upper()
    if upper_char in HERSHEY_SIMPLEX:
        HERSHEY_SIMPLEX[char] = HERSHEY_SIMPLEX[upper_char]


def get_glyph(char: str):
    """Safely retrieves a glyph representation, defaulting to space if unknown."""
    return HERSHEY_SIMPLEX.get(char, HERSHEY_SIMPLEX.get(char.upper(), HERSHEY_SIMPLEX[' ']))
